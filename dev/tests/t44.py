# 체험 공지·예시 활동 교체 · ⏱ 수업 타이머(교사 시작 → 학생 화면 맨 위, 멈춤·+1분·끝)
import asyncio, re
from playwright.async_api import async_playwright
U='file:///tmp/claude-0/smoke/p26.html'
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(); ctx=await b.new_context(viewport={'width':1280,'height':900}); await ctx.route(re.compile(r'https://.*'), lambda r: r.abort())
    errs=[]; W=lambda pg,ms=250: pg.wait_for_timeout(ms)
    D=await ctx.new_page(); D.on('pageerror',lambda e:errs.append('D:'+str(e)))
    await D.goto('file:///tmp/claude-0/smoke/pdemo.html?demo=1'); await W(D,700)
    await D.evaluate('S.tour=null; render()')
    print('notices:', await D.evaluate('S.courses.map(c=>c.title+" → "+c.notices.map(n=>n.text).join(" | "))'))
    print('demo rooms:', await D.evaluate('S.rooms.map(r=>r.title)'))
    print('relay qs:', await D.evaluate('S.posts.filter(p=>p.roomId==="comfort-relay").map(p=>p.questions[0].text)'))
    await D.evaluate('act("mcourse",{dataset:{v:"c-demo"}})'); await W(D,400)
    print('notice link:', await D.eval_on_selector_all('.tnotice a, .notices a','e=>e.map(x=>x.href)'))
    # 교사 타이머 (체험)
    await D.evaluate('act("open",{dataset:{id:"park-1965"}})'); await W(D,400)
    print('panel idle:', (await D.inner_text('.tmrpanel')).replace('\n',' '))
    await D.click('.tmrpanel [data-a=tmr-start][data-s="300"]'); await W(D,1300)
    print('running:', (await D.inner_text('.tmrpanel .tmr-t')), await D.evaluate('S.rooms.find(r=>r.id==="park-1965").timer.dur'))
    await D.screenshot(path='/tmp/claude-0/smoke/mob/tmr_teacher.png')
    await D.click('[data-a=tmr-pause]'); await W(D,1500); a=await D.inner_text('.tmrpanel .tmr-t'); await W(D,1200)
    print('paused stays:', a, await D.inner_text('.tmrpanel .tmr-t'), '| class:', await D.get_attribute('.tmrpanel','class'))
    await D.click('[data-a=tmr-add]'); await W(D,300); print('+1 paused:', await D.inner_text('.tmrpanel .tmr-t'))
    await D.click('[data-a=tmr-resume]'); await W(D,300)
    await D.evaluate('act("present",{dataset:{id:"park-1965"}})'); await W(D,600)
    print('present timer:', await D.inner_text('.ptmr')); await D.evaluate('act("present-exit",{dataset:{}})'); await W(D,300)
    await D.evaluate('act("open",{dataset:{id:"park-1965"}})'); await W(D,300)
    # 끝 상태: 시간을 지나간 것으로
    await D.evaluate('(()=>{const r=S.rooms.find(r=>r.id==="park-1965"); r.timer={...r.timer, endsAt:Date.now()+1500, left:null}; render()})()'); await W(D,2600)
    print('ended panel:', (await D.inner_text('.tmrpanel')).replace('\n',' ')[:60])
    await D.click('[data-a=tmr-stop]'); await W(D,300); print('stopped:', await D.evaluate('S.rooms.find(r=>r.id==="park-1965").timer'))
    # custom without minutes
    await D.click('.tmr-custom [data-a=tmr-start]'); await W(D,300); print('custom empty toast:', await D.evaluate('document.getElementById("toast")?.textContent'))
    await D.fill('#tmr-min','7'); await D.click('.tmr-custom [data-a=tmr-start]'); await W(D,400); print('custom 7:', await D.evaluate('S.rooms.find(r=>r.id==="park-1965").timer.dur/60000'))
    await D.evaluate('act("open",{dataset:{id:"demo-notes"}})'); await W(D,300); print('notes has panel:', bool(await D.query_selector('.tmrpanel')))
    # 실제 흐름: 교사 시작 → 학생 화면
    T=await ctx.new_page(); T.on('pageerror',lambda e:errs.append('T:'+str(e)))
    await T.goto(U+'?who=teacher'); await T.evaluate('localStorage.clear()'); await T.reload(); await W(T,700)
    await T.click('[data-a=roster-open]'); await W(T); await T.fill('#roster-add','10301 김가온'); await T.click('[data-a=roster-add]'); await W(T,500); await T.keyboard.press('Escape'); await W(T)
    code=(await T.evaluate('JSON.parse(localStorage.getItem("__sbmock"))'))['students'][0]['code']
    await T.click('.thead [data-a=create]'); await W(T); await T.fill('#c-prompt','콜럼버스의 날을 원주민의 날로 바꿔야 할까?')
    await T.click('[data-a=create-save]'); await W(T,700); rid=await T.evaluate('S.roomId')
    K=await ctx.new_page(); await K.set_viewport_size({'width':390,'height':844}); K.on('pageerror',lambda e:errs.append('K:'+str(e)))
    await K.goto(U+'?who=anon'); await W(K,500)
    await K.fill('#f-num','10301'); await K.fill('#f-name','김가온'); await K.fill('#f-code',code); await K.press('#f-code','Enter'); await W(K,1300)
    await K.evaluate(f'act("open",{{dataset:{{id:"{rid}"}}}})'); await W(K,500)
    print('student bar before:', bool(await K.query_selector('.tmrbar')))
    await T.click('.tmrpanel [data-a=tmr-start][data-s="600"]'); await W(T,800); await W(K,1500)
    print('student bar:', (await K.inner_text('.tmrbar')).replace('\n',' ') if await K.query_selector('.tmrbar') else None)
    await K.evaluate('scrollTo(0,600)'); await W(K,300)
    print('sticky top:', await K.evaluate('document.querySelector(".tmrbar").getBoundingClientRect().top'))
    await K.screenshot(path='/tmp/claude-0/smoke/mob/tmr_student.png')
    await K.click('[data-a=home]'); await W(K,400); await K.screenshot(path="/tmp/claude-0/smoke/mob/tmr_home.png"); print("home overflow:", await K.evaluate("document.documentElement.scrollWidth")); print("live bar:", await K.eval_on_selector_all(".livebar","e=>e.map(x=>x.innerText.replace(/\\n/g, \" \"))"))
    await K.evaluate(f'act("open",{{dataset:{{id:"{rid}"}}}})'); await W(K,300)
    await T.click('[data-a=tmr-stop]'); await W(T,600); await W(K,1200); print('student bar after stop:', bool(await K.query_selector('.tmrbar')))
    print('m overflow:', await K.evaluate('document.documentElement.scrollWidth'))
    print('errors', errs); await b.close()
asyncio.run(main())
