# 💬 실시간 토론 채팅: 만들기 → 학생 둘 입장(익명 닉네임·자동 배정) → 시작 → 실시간 메시지 → 삭제·제한 → 종료 → 투표 → 결과 → 성찰 → 포트폴리오
import asyncio, re
from playwright.async_api import async_playwright
U='file:///tmp/claude-0/smoke/p26.html'
